"""Coupling-mass relation of the scaling Yang-Lee model (Chapter 3, eq. after eq:fateev).

Al. B. Zamolodchikov, Int. J. Mod. Phys. A 10 (1995) 1125, Eq. (4.11) with the breather
mass (2.26), m_1 = 2 M sin(pi p / 2), at p = 2/3 (M(2,5) perturbed by Phi_13 = Phi_12).
Eq. (4.13): lambda = kappa_1(p) m_1^{4/(p+1)}; Table 4 gives kappa_1(2/3) = +-0.0970484562986085 i.
Output: kappa_1(2/3) and the coefficient c in m = c (-i g)^{5/12}.
Al. B. Zamolodchikov, Nucl. Phys. B 342 (1990) 695, Eq. (1.11), found c = 2.642944662... numerically.
"""
from mpmath import mp, mpf, gamma, sin, sqrt, pi

mp.dps = 30
p = mpf(2) / 3
pref = (p + 1) ** 2 / ((p - 1) * (2 * p - 1))
G = gamma(3 * p / (p + 1)) * gamma(p / (p + 1)) / (gamma((1 - 2 * p) / (p + 1)) * gamma(1 / (p + 1)))
M = 1 / (2 * sin(pi * p / 2))          # soliton mass M such that m_1 = 1
lam = -pref * sqrt(G + 0j) * (sqrt(pi) * M * gamma((p + 1) / 2) / (2 * gamma(p / 2))) ** (4 / (p + 1)) / pi
print("kappa_1(2/3) =", lam)
print("c = m / (-i g)^(5/12) =", (1 / (-1j * lam)) ** (mpf(5) / 12))
import sys
if "--tex" in sys.argv:
    # the constant to 10 decimals, as printed in Chapter 3 (never edit the output by hand)
    import os
    os.makedirs("generated", exist_ok=True)
    cval = ((1 / (-1j * lam)) ** (mpf(5) / 12)).real
    open("generated/yanglee_mass.tex", "w").write(
        "% Generated by code/yanglee_mass.py --tex. Do not edit.\n"
        f"\\newcommand{{\\YLmassConst}}{{{mp.nstr(cval, 11, strip_zeros=False)}}}\n")
