"""Lee--Yang zeroes of the periodic one-dimensional Ising chain (Chapter 1, figure).
x = e^{beta B}; zeta = x^2. x*T has polynomial entries; Tr (xT)^N = x^N Z_N is a polynomial in zeta.
Prints the zeroes as TikZ coordinates on the unit circle, and checks |zeta|=1 and the edge."""
import numpy as np
from numpy.polynomial import polynomial as P
import sys
K, N = 0.5, 24
eK, emK = np.exp(K), np.exp(-K)
# matrix entries as polynomials in x (coefficient lists, lowest first)
T = [[[0, 0, eK], [0, emK]], [[0, emK], [eK]]]
def mmul(A, B):
    return [[P.polyadd(P.polymul(A[i][0], B[0][j]), P.polymul(A[i][1], B[1][j])) for j in range(2)] for i in range(2)]
M = T
for _ in range(N - 1):
    M = mmul(M, T)
tr = P.polyadd(M[0][0], M[1][1])          # polynomial in x, even powers only
c = np.array(tr)[0::2]                    # polynomial in zeta
roots = P.polyroots(c)
print("max | |zeta|-1 | =", np.max(np.abs(np.abs(roots) - 1)), file=sys.stderr)
ang = np.angle(roots)
phi_e = np.arcsin(np.exp(-2 * K))
print("min |arg zeta| =", np.min(np.abs(ang)), " predicted edge 2*phi_e =", 2 * phi_e, file=sys.stderr)
for a in sorted(ang):
    print(f"({np.cos(a):.4f},{np.sin(a):.4f})", end=" ")
print()
if "--tex" in sys.argv:
    # write the coordinates for the figure of Chapter 1 (never edit the output by hand)
    import os
    os.makedirs("generated", exist_ok=True)
    pts = ",".join(f"({np.cos(a):.4f},{np.sin(a):.4f})" for a in sorted(ang))
    open("generated/ising1d_zeroes.tex", "w").write(
        f"% Generated by code/ising1d_zeroes.py --tex (K = {K}, N = {N}). Do not edit.\n"
        f"\\newcommand{{\\IsingChainZeroes}}{{{pts}}}\n")
